// Mise au point : le joueur monte en voiture et roule ; captures successives.
import { chromium } from 'playwright';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { serve } from './server.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
const out = process.argv[2] ?? '/tmp';
const { server, url } = await serve(path.join(here, '..', 'dist'));
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(url);
await page.waitForFunction(() => window.__klaxo && window.__klaxo.scene, null, { timeout: 30000 });
await page.evaluate(() => { const g = window.__klaxo; g.settings.shownStorageNotice = true; g.settings.quality = 'high'; g.applySettings(); g.newGame({ ...g.world.player.look }, 'Testeur'); });
await page.waitForTimeout(800);
await page.evaluate(() => { const g = window.__klaxo; g.debug.tp('x_centre', 40, 60); const v = g.debug.car('sport'); g.world.player.x = v.x + 4; g.world.player.y = v.y + 14; });
await page.waitForTimeout(600);
await page.screenshot({ path: path.join(out, 'drive0.png') });
await page.keyboard.press('KeyE');
await page.waitForTimeout(700);
console.log(JSON.stringify(await page.evaluate(() => window.__klaxo.debug.state())));
await page.keyboard.down('KeyW');
await page.waitForTimeout(1800);
await page.screenshot({ path: path.join(out, 'drive1.png') });
await page.keyboard.down('KeyD');
await page.waitForTimeout(500);
await page.keyboard.up('KeyD');
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(out, 'drive2.png') });
await page.keyboard.up('KeyW');
await page.evaluate(() => window.__klaxo.debug.wanted(3));
await page.waitForTimeout(6000);
await page.screenshot({ path: path.join(out, 'drive3.png') });
console.log(JSON.stringify(await page.evaluate(() => window.__klaxo.debug.state())), errors);
await browser.close(); server.close();
